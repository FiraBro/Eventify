package main

import (
	"context"
	"errors"
	"fmt"
	"log/slog"
	"net"
	"net/http"
	"os"
	"os/signal"
	"syscall"

	"github.com/gin-gonic/gin"
	"github.com/joho/godotenv"
	swaggerFiles "github.com/swaggo/files"
	ginSwagger "github.com/swaggo/gin-swagger"

	_ "github.com/FiraBro/local-go/docs" // Generated by swag init.

	"github.com/FiraBro/local-go/internal/cacheaside"
	"github.com/FiraBro/local-go/internal/config"
	"github.com/FiraBro/local-go/internal/db"
	"github.com/FiraBro/local-go/internal/gateways"
	"github.com/FiraBro/local-go/internal/handlers"
	"github.com/FiraBro/local-go/internal/middlewares"
	"github.com/FiraBro/local-go/internal/observability"
	"github.com/FiraBro/local-go/internal/repositories"
	"github.com/FiraBro/local-go/internal/routes"
	"github.com/FiraBro/local-go/internal/services"
)

const apiBasePath = "/api/v1"

// @title           Local-Go API Engine
// @version         1.0
// @description     Interactive live API documentation for the local-go ecosystem.
// @host            localhost:8080
// @BasePath        /api/v1
func main() {
	if err := run(); err != nil {
		slog.Error("application stopped with an error", "error", err)
		os.Exit(1)
	}
}

func run() error {
	// 1. Environment and validated configuration
	envErr := godotenv.Load()
	config.ValidateConfig()
	logger, err := observability.NewJSONLogger(config.AppConfig.LogLevel, os.Stdout)
	if err != nil {
		return err
	}
	slog.SetDefault(logger)
	if envErr != nil {
		logger.Info(".env file not found; using environment variables")
	}

	// 2. PostgreSQL is essential; fail startup cleanly if it cannot be opened.
	dbConn, err := db.OpenDB()
	if err != nil {
		return fmt.Errorf("initialize PostgreSQL: %w", err)
	}
	defer func() {
		if err := dbConn.Close(); err != nil {
			logger.Error("failed to close PostgreSQL connection pool", "error", err)
		}
	}()

	// 3. Repositories
	userRepo := repositories.NewUserRepository(dbConn)
	staffRepo := repositories.NewStaffRepository(dbConn)
	serviceRepo := repositories.NewServiceRepository(dbConn)
	bookingRepo := repositories.NewBookingRepository(dbConn)
	paymentRepo := repositories.NewPaymentRepository(dbConn)
	notificationRepo := repositories.NewNotificationRepository(dbConn)
	refreshRepo := repositories.NewRefreshTokenRepository(dbConn)
	resetRepo := repositories.NewResetTokenRepository(dbConn)
	reportRepo := repositories.NewReportRepository(dbConn)
	settingsRepo := repositories.NewSettingsRepository(dbConn)
	logRepo := repositories.NewLogRepository(dbConn)

	// 4. Initialize Redis for best-effort read caching.
	// Redis is an optimization, not a requirement for serving requests.
	var readCache cacheaside.Store

	if err := config.InitRedis(); err != nil {
		logger.Warn("Redis unavailable; continuing with fail-open behavior")

		// InitRedis creates the client before pinging it.
		// Close it if initialization fails.
		if config.RedisClient != nil {
			if closeErr := config.RedisClient.Close(); closeErr != nil {
				logger.Warn("failed to close unavailable Redis client", "error", closeErr)
			}
			config.RedisClient = nil
		}
	}

	if config.RedisClient != nil {
		readCache = cacheaside.RedisStore{
			Client: config.RedisClient,
		}

		defer func() {
			if err := config.RedisClient.Close(); err != nil {
				logger.Error("failed to close Redis client", "error", err)
			}
		}()
	}

	// 5. Gateways
	chapaGateway := gateways.NewChapaGateway(
		os.Getenv("CHAPA_SECRET_KEY"),
		os.Getenv("CHAPA_WEBHOOK_SECRET"),
	)

	// 6. Services
	authService := services.NewAuthService(
		userRepo,
		refreshRepo,
		resetRepo,
	)
	staffService := services.NewStaffService(staffRepo, serviceRepo)
	availabilityService := services.NewAvailabilityService(staffRepo)
	serviceService := services.NewServiceService(serviceRepo)
	bookingService := services.NewBookingService(bookingRepo, serviceRepo)

	paymentService := services.NewPaymentService(
		paymentRepo,
		bookingRepo,
		serviceRepo,
		chapaGateway,
		services.PaymentConfig{
			CallbackURL: os.Getenv("CHAPA_CALLBACK_URL"),
			ReturnURL:   os.Getenv("CHAPA_RETURN_URL"),
			Currency:    "ETB",
		},
	)

	notificationService := services.NewNotificationService(notificationRepo)
	reportService := services.NewReportService(reportRepo)
	settingsService := services.NewSettingsService(settingsRepo)
	logService := services.NewLogService(logRepo)

	// Enable cache-aside for exactly the three C2 read paths.
	availabilityService.SetReadCache(readCache)
	serviceService.SetReadCache(readCache)
	settingsService.SetReadCache(readCache)
	staffService.SetReadCache(readCache)
	bookingService.SetReadCache(readCache)

	// 7. Handlers
	authHandler := handlers.NewAuthHandler(authService)
	staffHandler := handlers.NewStaffHandler(staffService, availabilityService)
	serviceHandler := handlers.NewServiceHandler(serviceService)
	bookingHandler := handlers.NewBookingHandler(bookingService)
	paymentHandler := handlers.NewPaymentHandler(paymentService)
	notificationHandler := handlers.NewNotificationHandler(notificationService)
	reportHandler := handlers.NewReportHandler(reportService)
	settingsHandler := handlers.NewSettingsHandler(settingsService)
	logHandler := handlers.NewLogHandler(logService)

	// 8. Router setup
	if os.Getenv("GIN_MODE") == "" && os.Getenv("APP_ENV") == "production" {
		gin.SetMode(gin.ReleaseMode)
	}

	r := gin.New()

	if err := r.SetTrustedProxies(nil); err != nil {
		return fmt.Errorf("configure trusted proxies: %w", err)
	}

	metrics := observability.NewMetrics()
	r.Use(
		middlewares.RequestID(),
		middlewares.HTTPObservability(logger, metrics),
		middlewares.Recovery(logger),
		middlewares.SecurityHeaders(),
		middlewares.ExplicitCORS(),
		middlewares.RequestBodyLimiter(),
	)

	// Operational endpoints stay outside the versioned business API.
	r.GET("/healthz", handlers.Healthz)
	r.GET("/readyz", handlers.Readyz(dbConn, config.AppConfig.HealthCheckTimeout))
	r.GET("/metrics", gin.WrapH(metrics.Handler()))

	// 8b. API routes
	api := r.Group(apiBasePath)

	routes.AuthRoutes(api, authHandler, userRepo)
	routes.UserRoutes(api, authHandler, userRepo)
	routes.StaffRoutes(api, staffHandler, userRepo)
	routes.ServiceRoutes(api, serviceHandler, userRepo)
	routes.BookingRoutes(api, bookingHandler, userRepo)
	routes.PaymentRoutes(api, paymentHandler, userRepo)
	routes.NotificationRoutes(api, notificationHandler, userRepo)
	routes.ReportRoutes(api, reportHandler, userRepo)
	routes.SettingsRoutes(api, settingsHandler, userRepo)
	routes.LogRoutes(api, logHandler, userRepo)

	// Swagger UI is disabled in production.
	if os.Getenv("APP_ENV") != "production" {
		r.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))
	}

	// 9. HTTP server configuration
	port := config.AppConfig.Port
	appCtx, cancelApp := context.WithCancel(context.Background())
	defer cancelApp()

	srv := &http.Server{
		Addr:              ":" + port,
		Handler:           r,
		ReadHeaderTimeout: config.AppConfig.ReadHeaderTimeout,
		ReadTimeout:       config.AppConfig.ReadTimeout,
		WriteTimeout:      config.AppConfig.WriteTimeout,
		IdleTimeout:       config.AppConfig.IdleTimeout,
		MaxHeaderBytes:    1 << 20,
		BaseContext: func(net.Listener) context.Context {
			return appCtx
		},
	}

	// 10. Start the HTTP server and monitor termination signals.
	serverErrors := make(chan error, 1)
	serverDone := make(chan struct{})
	go func() {
		defer close(serverDone)
		logger.Info("HTTP server starting", "port", port, "base_path", apiBasePath)
		if config.AppConfig.AppEnv != "production" {
			logger.Info("Swagger documentation enabled", "route", "/swagger/*any")
		}
		if err := srv.ListenAndServe(); err != nil && !errors.Is(err, http.ErrServerClosed) {
			serverErrors <- err
		}
	}()

	signalCtx, stopSignals := signal.NotifyContext(context.Background(), syscall.SIGINT, syscall.SIGTERM)
	defer stopSignals()
	var runErr error
	select {
	case <-signalCtx.Done():
		logger.Info("shutdown signal received")
	case err := <-serverErrors:
		logger.Error("HTTP server failed", "error", err)
		runErr = err
	}

	if shutdownErr := observability.ShutdownHTTPServer(srv, config.AppConfig.ShutdownTimeout, cancelApp, logger); shutdownErr != nil && runErr == nil {
		runErr = shutdownErr
	}
	<-serverDone
	logger.Info("application shutdown complete")
	return runErr
}
